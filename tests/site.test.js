const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const robots = fs.readFileSync('robots.txt', 'utf8');
const sitemap = fs.readFileSync('sitemap.xml', 'utf8');
const headers = fs.readFileSync('_headers', 'utf8');
assert.match(html, /<main id="main-content">/);
assert.match(html, /<a href="#main-content" class="skip-link">/);
assert.match(html, /rel="canonical" href="https:\/\/norulesound\.com\/"/);
assert.match(html, /hreflang="en"/);
assert.match(html, /<meta name="description"/);
assert.match(robots, /^User-agent: \*/m);
assert.match(robots, /Sitemap: https:\/\/norulesound\.com\/sitemap\.xml/);
assert.match(sitemap, /<loc>https:\/\/norulesound\.com\/<\/loc>/);
assert.match(headers, /Content-Security-Policy:/);
assert.match(headers, /X-Content-Type-Options: nosniff/);
const window = {};
vm.runInNewContext(fs.readFileSync('js/security.js', 'utf8'), {window, URL});
const {httpsURL, spotify, email} = window.NRS_SECURITY;
assert.equal(httpsURL('javascript:alert(1)'), '');
assert.equal(httpsURL('https://soundcloud.com.evil.example/track', ['soundcloud.com']), '');
assert.equal(httpsURL('https://user:password@soundcloud.com/x'), '');
assert.equal(httpsURL('https://soundcloud.com:8443/x'), '');
assert.equal(httpsURL('https://soundcloud.com/test', ['soundcloud.com']), 'https://soundcloud.com/test');
assert.equal(spotify('https://open.spotify.com/playlist/abc123'), 'https://open.spotify.com/embed/playlist/abc123');
assert.equal(spotify('https://evil.example/playlist/abc123'), '');
assert.equal(email('wrong\r\nBcc:evil@example.com'), '');
console.log('Static SEO and URL validation checks passed');
